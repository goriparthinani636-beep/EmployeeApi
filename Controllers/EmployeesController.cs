using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using EmployeeApi.Data;
using EmployeeApi.Models;

namespace EmployeeApi.Controllers;

[ApiController]
[Route("api/[controller]")]
public class EmployeesController : ControllerBase
{
    private readonly AppDbContext _context;

    public EmployeesController(AppDbContext context)
    {
        _context = context;
    }

    // 1. GET: /api/employees
    [HttpGet]
    public async Task<IActionResult> GetAll()
    {
        var employees = await _context.Employees
            .OrderByDescending(e => e.Id)
            .ToListAsync();
        return Ok(employees);
    }

    // 2. GET: /api/employees/{id}
    [HttpGet("{id}")]
    public async Task<IActionResult> GetById(int id)
    {
        var employee = await _context.Employees.FindAsync(id);
        if (employee == null)
            return NotFound(new { message = $"Employee with ID {id} not found." });

        return Ok(employee);
    }

    // 3. POST: /api/employees
    [HttpPost]
    public async Task<IActionResult> Create([FromBody] Employee employee)
    {
        if (employee == null)
            return BadRequest(new { message = "Invalid employee data." });

        // Ensure Id is generated by database
        employee.Id = 0;
        if (employee.JoiningDate == default)
        {
            employee.JoiningDate = DateTime.UtcNow;
        }

        _context.Employees.Add(employee);
        await _context.SaveChangesAsync();

        return CreatedAtAction(nameof(GetById), new { id = employee.Id }, employee);
    }

    // 4. PUT: /api/employees/{id}
    [HttpPut("{id}")]
    public async Task<IActionResult> Update(int id, [FromBody] Employee updated)
    {
        var existing = await _context.Employees.FindAsync(id);
        if (existing == null)
            return NotFound(new { message = $"Employee with ID {id} not found." });

        existing.FirstName = updated.FirstName;
        existing.LastName = updated.LastName;
        existing.Email = updated.Email;
        existing.Phone = updated.Phone;
        existing.Department = updated.Department;
        existing.Designation = updated.Designation;
        existing.Status = updated.Status;

        await _context.SaveChangesAsync();
        return Ok(existing);
    }

    // 5. DELETE: /api/employees/{id}
    [HttpDelete("{id}")]
    public async Task<IActionResult> Delete(int id)
    {
        var existing = await _context.Employees.FindAsync(id);
        if (existing == null)
            return NotFound(new { message = $"Employee with ID {id} not found." });

        _context.Employees.Remove(existing);
        await _context.SaveChangesAsync();

        return NoContent();
    }
}